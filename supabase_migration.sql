-- Wedding Reception Dashboard — Supabase schema + realtime setup
-- Run this once in the Supabase SQL Editor (Project → SQL Editor → New query).
--
-- SECURITY NOTE: this app has no login/auth layer — it's a small internal
-- tool for reception staff. The policies below allow the public "anon" key
-- (the one embedded in the deployed frontend) to read AND write both
-- tables. Anyone who has the app URL can see and edit guest data. That's
-- an acceptable tradeoff for a one-off private event tool, but don't reuse
-- this schema/policy pattern for anything with sensitive data.

-- ── Tables ───────────────────────────────────────────────
create table if not exists public.tables (
  id         text primary key,        -- e.g. '1', '3A', 'VIP', 'R'
  name       text not null,           -- e.g. 'Table 3A', 'VIP Table'
  capacity   int  not null default 10,
  label      text not null default '',
  sort_order int  not null,           -- display order (VIP first, R last, etc.)
  updated_at timestamptz not null default now()
);

create table if not exists public.guests (
  id           bigint generated by default as identity primary key,
  table_id     text not null references public.tables(id) on delete cascade,
  name         text not null default '',
  checked_in   boolean not null default false,
  ang_bao      boolean not null default false,
  ang_bao_amt  numeric,
  walk_in      boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists guests_table_id_idx on public.guests (table_id);

-- ── Row Level Security ───────────────────────────────────
alter table public.tables enable row level security;
alter table public.guests enable row level security;

drop policy if exists "tables_anon_all" on public.tables;
create policy "tables_anon_all" on public.tables
  for all to anon using (true) with check (true);

drop policy if exists "guests_anon_all" on public.guests;
create policy "guests_anon_all" on public.guests
  for all to anon using (true) with check (true);

-- ── Realtime ─────────────────────────────────────────────
-- Broadcasts INSERT/UPDATE/DELETE on these tables to every subscribed client.
alter publication supabase_realtime add table public.tables;
alter publication supabase_realtime add table public.guests;

